"""Fit the picture to the user's voice-over (ElevenLabs), in English or Malayalam:
    python3 films/spider/align.py [en|ml]   (reads audio/voice.mp3 for en, audio/voice-ml.mp3 for ml)
The transcriber can't download its model here, so the 17 script lines are found from the pauses: candidate cuts are the
silences (ffmpeg silencedetect), and a dynamic program picks the 16 that best match each line's share of the letters.
Each line is then laid out with a short breath between lines, and src/timing.js gets two tables:
  VOICE = the start of each line in the final film, PLAN = the same lines in the planned picture timeline.
FILM.draw maps film time -> planned time piecewise linearly, so every scene stretches or shrinks to its line.
    python3 films/spider/align.py [en|ml]  ->  audio/voice-aligned.wav, src/timing.js"""
import os, re, subprocess, json, sys
import numpy as np, wave

here = os.path.dirname(os.path.abspath(__file__))
LANG = sys.argv[1] if len(sys.argv) > 1 else 'en'
src = os.path.join(here, 'audio', 'voice.mp3' if LANG == 'en' else 'voice-ml.mp3')
PLAN = [0, 10, 22, 32, 44, 56, 70, 84, 100, 114, 126, 146, 160, 172, 186, 200, 212, 220]
LEAD, GAP, TAIL, SR = 0.35, 0.6, 1.6, 48000

# the voice as mono float samples
raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', src, '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
x = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
total = len(x) / SR

# pauses
log = subprocess.run(['ffmpeg', '-hide_banner', '-i', src, '-af', 'silencedetect=noise=-35dB:d=0.3', '-f', 'null', '-'], capture_output=True, text=True).stderr
st = [float(v) for v in re.findall(r'silence_start: ([0-9.]+)', log)]; en = [float(v) for v in re.findall(r'silence_end: ([0-9.]+)', log)]
cands = [(a + b) / 2 for a, b in zip(st, en)]

# the script lines and their expected ends (by letters)
txt = open(os.path.join(here, 'script-timed.md')).read().split('## Plain lines')[0]
en_part, ml_part = txt.split('## മലയാളം')
lines = [m.group(1) for m in (re.match(r'\| \d+ \| [^|]+ \| (.+) \|', l) for l in (en_part if LANG == 'en' else ml_part).splitlines()) if m]
assert len(lines) == 17, len(lines)
chars = [len(re.sub(r'[\s.,:;?!\-"\'()]', '', s)) for s in lines]
cum = np.cumsum(chars) / sum(chars) * total
# choose the 19 cuts so every line is spoken at a plausible, even pace: cost = sum of log(rate / mean rate)^2 per line,
# minus a bonus for longer pauses (line breaks are usually the longer breaths). DP over (line, cut).
dur = {round((a + b) / 2, 3): b - a for a, b in zip(st, en)}
P = [0.0] + cands + [total]; PD = [0.0] + [dur[round(c, 3)] for c in cands] + [0.0]; m = len(P)
mean = sum(chars) / total; INF = 1e18
cost = lambda i, j0, j1: (np.log(max(1e-3, chars[i] / max(0.3, P[j1] - P[j0])) / mean)) ** 2
dp = [[INF] * m for _ in range(17)]; bk = [[-1] * m for _ in range(17)]
for j in range(1, m - 1): dp[0][j] = cost(0, 0, j) - 0.6 * PD[j]
for i in range(1, 16):
    for j in range(i + 1, m - 1):
        for k in range(i, j):
            if dp[i - 1][k] < INF:
                v = dp[i - 1][k] + cost(i, k, j) - 0.6 * PD[j]
                if v < dp[i][j]: dp[i][j], bk[i][j] = v, k
best, bj = INF, -1
for k in range(16, m - 1):
    v = dp[15][k] + cost(16, k, m - 1)
    if v < best: best, bj = v, k
sel = []; j = bj
for i in range(15, -1, -1): sel.append(j); j = bk[i][j]
cuts = [0.0] + [P[j] for j in reversed(sel)] + [total]
# overrides after inspecting the pauses: {line index after which the cut falls: time near the right pause}
# overrides after checking the words/second per line: {line index after which the cut falls: exact time}
FIX = {}
for k, at in FIX.items(): cuts[k] = at
for i in range(17): print(f'   line {i + 1:2d}: {chars[i] / (cuts[i + 1] - cuts[i]):.1f} units/s')

# lay the lines out with breaths between them
out, starts, at = [np.zeros(int(LEAD * SR), np.float32)], [], LEAD
for i in range(17):
    seg = x[int(cuts[i] * SR):int(cuts[i + 1] * SR)]
    starts.append(at); out.append(seg); at += len(seg) / SR
    if i < 16: out.append(np.zeros(int(GAP * SR), np.float32)); at += GAP
end = at; out.append(np.zeros(int(TAIL * SR), np.float32)); D = end + TAIL
y = np.concatenate(out)
with wave.open(os.path.join(here, 'audio', 'voice-aligned.wav'), 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(y, -1, 1) * 32767).astype(np.int16).tobytes())
# film windows: a line's window runs from its start (minus half a breath) to the next line's
VOICE = [0.0] + [s - GAP / 2 for s in starts[1:]] + [D]
with open(os.path.join(here, 'src', 'timing.js'), 'w') as f:
    f.write('// generated by align.py from audio/voice.mp3: line windows in the film (VOICE) and in the planned picture (PLAN)\n')
    f.write(f'const TIMING = {json.dumps({"VOICE": [round(v, 3) for v in VOICE], "PLAN": PLAN, "D": round(D, 3), "starts": [round(s, 3) for s in starts]})};\n')
for i in range(17): print(f'{i + 1:2d}  film {VOICE[i]:6.2f}-{VOICE[i + 1]:6.2f}  voice {cuts[i]:6.2f}-{cuts[i + 1]:6.2f}  {lines[i][:46]}')
print(f'duration {D:.2f}s')
